const assert = require('node:assert/strict');
const { createHash } = require('node:crypto');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');

(async () => {
  const { openCatalog, upsertGames } = await import('../../backend/src/catalog/catalog.js');
  const { createApp } = await import('../../backend/src/server.js');
  const { createServer } = await import('../../frontend/node_modules/vite/dist/node/index.js');
  const db = openCatalog(':memory:');
  for (const [id, name] of [[1, 'Ana'], [2, 'Bruno'], [3, 'Jogador com um nome bastante longo para testar a quebra de linha']]) {
    db.prepare('INSERT INTO users VALUES (?,?,?,?,?)').run(id, name, `private${id}@example.com`, 'unused', 'unused');
  }
  upsertGames(db, [{ id: 1, name: 'Hollow Knight', platforms: [{ name: 'PC' }], genres: [{ name: 'Adventure' }] }, { id: 2, name: 'Celeste', platforms: [{ name: 'PC' }] }]);
  db.prepare('INSERT INTO user_favorites VALUES (2,1), (2,2)').run();
  db.prepare('INSERT INTO user_ratings VALUES (2,1,5), (1,1,1)').run();
  db.prepare("INSERT INTO comments(user_id,game_id,body,created_at) VALUES (2,1,'Um mundo que dá vontade de explorar por inteiro.','2026-11-05T12:00:00Z')").run();
  const token = 'c'.repeat(64);
  db.prepare('INSERT INTO sessions VALUES (?,?,?)').run(createHash('sha256').update(token).digest('hex'), 1, Date.now() + 600000);
  const api = createApp(db);
  await new Promise(resolve => api.listen(0, '127.0.0.1', resolve));
  const server = await createServer({ root: 'frontend', server: { host: '127.0.0.1', port: 0, proxy: { '/api': `http://127.0.0.1:${api.address().port}` } } });
  await server.listen();
  const origin = `http://127.0.0.1:${server.httpServer.address().port}`;
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  try {
    const context = await browser.newContext({ viewport: { width: 1280, height: 900 } });
    await context.addCookies([{ name: 'bg_session', value: token, url: origin }]);
    await context.addInitScript(() => localStorage.setItem('buscagames:cookie-choice', 'rejected'));
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    async function captureMotion(selector, region, file) {
      const button = page.locator(selector);
      await page.locator(`${selector}[data-celebrating]`).waitFor();
      const animations = await button.evaluate(element => {
        const running = element.getAnimations({ subtree: true });
        const names = running.map(animation => animation.animationName).filter(Boolean);
        running.forEach(animation => { animation.pause(); animation.currentTime = 220; });
        return names;
      });
      assert(animations.includes('social-confirm-icon'));
      assert(animations.includes('social-confirm-halo'));
      await page.locator(region).screenshot({ path: file });
      await button.evaluate(element => element.getAnimations({ subtree: true }).forEach(animation => animation.finish()));
      await page.locator(`${selector}[data-celebrating]`).waitFor({ state: 'detached' });
    }
    await page.goto(`${origin}/comunidade`);
    await page.getByRole('heading', { name: 'Bruno', exact: true }).waitFor();
    await page.getByRole('searchbox').fill('Bruno');
    await page.getByRole('button', { name: 'Buscar', exact: true }).click();
    await page.waitForURL('**/comunidade?q=Bruno');
    await page.getByRole('heading', { name: 'Bruno', exact: true }).click();
    await page.getByText('Nota de Bruno: 5/5').waitFor();
    assert.equal(await page.getByText('private2@example.com').count(), 0);
    await page.evaluate(() => document.fonts.ready);
    const followWidth = (await page.locator('.social-button--follow').boundingBox()).width;
    assert.equal(await page.locator('[data-celebrating]').count(), 0);
    let releaseFollow;
    const heldFollow = new Promise(resolve => { releaseFollow = resolve; });
    await page.route('**/api/users/2/follow', async route => { await heldFollow; await route.continue(); }, { times: 1 });
    await page.getByRole('button', { name: 'Seguir', exact: true }).focus();
    await page.keyboard.press('Enter');
    await page.getByRole('button', { name: 'Salvando…', exact: true }).waitFor();
    assert.equal(await page.locator('.social-button--follow').isDisabled(), true);
    assert.equal(await page.locator('[data-celebrating]').count(), 0);
    assert(Math.abs((await page.locator('.social-button--follow').boundingBox()).width - followWidth) < 1);
    releaseFollow();
    await page.getByRole('link', { name: 'Seguidores (1)' }).waitFor();
    await captureMotion('.social-button--follow', '.community-profile', 'evidencias/capturas/social-follow-desktop.png');
    assert(Math.abs((await page.locator('.social-button--follow').boundingBox()).width - followWidth) < 1);
    await page.reload();
    await page.getByRole('button', { name: 'Deixar de seguir' }).waitFor();
    await page.screenshot({ path: 'evidencias/capturas/community-desktop.png', fullPage: true });
    await page.getByRole('link', { name: 'Seguidores (1)' }).click();
    await page.getByRole('heading', { name: 'Ana', exact: true }).waitFor();
    await page.getByRole('link', { name: 'Biblioteca', exact: true }).click();
    await page.getByRole('button', { name: 'Avaliados', exact: true }).click();
    await page.waitForURL('**/perfil/2?filtro=rated');
    await page.getByRole('heading', { name: 'Celeste', exact: true }).waitFor({ state: 'detached' });
    await page.getByText('Nota de Bruno: 5/5').waitFor();
    assert.equal(await page.getByRole('heading', { name: 'Celeste', exact: true }).count(), 0);
    await page.getByRole('link', { name: /Conversar sobre o jogo/ }).click();
    await page.getByText('Um mundo que dá vontade de explorar por inteiro.').waitFor();
    const like = page.getByRole('button', { name: /^Curtir/ });
    const likeWidth = (await like.boundingBox()).width;
    await like.click();
    await page.getByRole('button', { name: /^Descurtir/ }).waitFor();
    await captureMotion('.social-button--like', '.comment-items li', 'evidencias/capturas/social-like-desktop.png');
    assert(Math.abs((await page.locator('.social-button--like').boundingBox()).width - likeWidth) < 1);
    assert.equal(db.prepare('SELECT COUNT(*) AS n FROM comment_likes').get().n, 1);
    await page.reload();
    await page.getByRole('button', { name: /^Descurtir/ }).click();
    await page.getByRole('button', { name: /^Curtir/ }).waitFor();
    assert.equal(await page.locator('[data-celebrating]').count(), 0);
    assert.equal(db.prepare('SELECT COUNT(*) AS n FROM comment_likes').get().n, 0);
    await page.setViewportSize({ width: 360, height: 800 });
    await page.getByRole('button', { name: /^Curtir/ }).focus();
    await page.keyboard.press('Space');
    await captureMotion('.social-button--like', '.comment-items li', 'evidencias/capturas/social-like-mobile.png');
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.getByRole('button', { name: /^Descurtir/ }).click();
    await page.getByRole('button', { name: /^Curtir/ }).waitFor();
    await page.locator('.comment-author').filter({ hasText: 'Bruno' }).click();
    await page.getByRole('button', { name: 'Deixar de seguir' }).waitFor();
    await page.setViewportSize({ width: 360, height: 800 });
    await page.screenshot({ path: 'evidencias/capturas/community-mobile.png', fullPage: true });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    // A real API mutation is intercepted only for the failure/retry state.
    await page.route('**/api/users/2/follow', route => route.fulfill({ status: 503, json: { error: 'Falha temporária. Tente novamente.' } }));
    await page.getByRole('button', { name: 'Deixar de seguir' }).click();
    await page.getByRole('alert').filter({ hasText: 'Falha temporária.' }).waitFor();
    assert.equal(db.prepare('SELECT COUNT(*) AS n FROM user_follows').get().n, 1);
    await page.unroute('**/api/users/2/follow');
    await page.getByRole('button', { name: 'Deixar de seguir' }).click();
    await page.getByRole('button', { name: 'Seguir', exact: true }).waitFor();
    await context.setOffline(true);
    await page.getByRole('button', { name: 'Seguir', exact: true }).click();
    await page.getByRole('alert').filter({ hasText: 'Falha de comunicação.' }).waitFor();
    await context.setOffline(false);
    await page.getByRole('button', { name: 'Seguir', exact: true }).click();
    await page.getByRole('button', { name: 'Deixar de seguir' }).waitFor();
    await captureMotion('.social-button--follow', '.community-profile', 'evidencias/capturas/social-follow-mobile.png');
    await page.emulateMedia({ reducedMotion: 'reduce' });
    await page.getByRole('button', { name: 'Deixar de seguir' }).click();
    await page.getByRole('button', { name: 'Seguir', exact: true }).click();
    await page.getByRole('button', { name: 'Deixar de seguir' }).waitFor();
    assert.equal(await page.locator('.social-button--follow').evaluate(element => element.getAnimations({ subtree: true }).length), 0);
    await page.emulateMedia({ reducedMotion: 'no-preference' });
    await page.goto(`${origin}/perfil/3`);
    await page.getByText('Nada por aqui ainda.').waitFor();
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.goto(`${origin}/perfil/999`);
    await page.getByText('Jogador não encontrado.').waitFor();
    await page.goto(`${origin}/perfil/1`);
    await page.getByText(/Este é o seu perfil público/).waitFor();
    assert.equal(await page.getByRole('button', { name: 'Seguir', exact: true }).count(), 0);
    await page.getByRole('link', { name: 'Seguindo (1)' }).click();
    await page.getByRole('button', { name: 'Deixar de seguir' }).click();
    await page.getByRole('link', { name: 'Seguindo (0)' }).waitFor();
    await page.getByText('Nada por aqui ainda.').waitFor();
    // Expired session opens the existing login dialog without making the mutation.
    await page.goto(`${origin}/perfil/2`);
    await page.getByRole('button', { name: 'Seguir', exact: true }).waitFor();
    db.prepare('DELETE FROM sessions').run();
    await page.getByRole('button', { name: 'Seguir', exact: true }).click();
    await page.getByRole('dialog').waitFor();
    await page.keyboard.press('Escape');
    await page.getByRole('dialog').waitFor({ state: 'hidden' });
    await page.emulateMedia({ reducedMotion: 'reduce' });
    await page.goto(`${origin}/comunidade`);
    await page.getByRole('heading', { name: 'Bruno', exact: true }).waitFor();
    await page.setViewportSize({ width: 320, height: 700 });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.getByRole('searchbox').fill('sem resultados');
    await page.getByRole('button', { name: 'Buscar', exact: true }).click();
    await page.getByText('Nada por aqui ainda.').waitFor();
    await page.getByRole('button', { name: 'Limpar busca de jogadores' }).click();
    await page.getByRole('heading', { name: 'Bruno', exact: true }).waitFor();
    await page.waitForFunction(() => document.querySelector('#player-search') === document.activeElement);
    assert.deepEqual(errors, []);
    console.log('PASS: real API/database; profile, library, follows, likes, persistence, owner isolation, search, keyboard, mobile 320/360px, offline/retry, empty/404, session expiration, reduced motion.');
  } finally { await browser.close(); await server.close(); await new Promise(resolve => api.close(resolve)); db.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
